// Writes docs/design-system/manifest.md: every component of the design system with its description, props,
// events, slots and exposed methods, read from the .vue files themselves (vue-component-meta). The manifest is
// what coding agents read before they build UI; `--check` fails when it is out of date.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createChecker } from 'vue-component-meta';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const base = join(root, 'src/renderer/design-system');
const target = join(root, 'docs/design-system/manifest.md');
const LEVELS = [
  ['atoms', 'Atoms', 'The smallest parts, built from HTML and tokens only.'],
  ['molecules', 'Molecules', 'A few atoms that do one thing together.'],
  ['organisms', 'Organisms', 'Self-contained sections of the interface.'],
  ['templates', 'Templates', 'Arrangements of organisms without content of their own.'],
  ['pages', 'Pages', 'A template filled with the real application state.'],
];

const checker = createChecker(join(root, 'tsconfig.app.json'), { forceUseTs: true, printer: { newLine: 1 } });
const cell = (text) => String(text ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();
const code = (text) => `\`${String(text).replace(/`/g, "'").replace(/\|/g, '\\|')}\``;
const description = (file) => /^<!--\s*@component\s+([\s\S]*?)\s*-->/.exec(readFileSync(file, 'utf8'))?.[1].replace(/\s+/g, ' ') ?? '';

export function buildManifest() {
  const lines = [
    '# Design system manifest',
    '',
    'Generated by `npm run design-system:manifest` from the components in `src/renderer/design-system`. Do not edit by hand.',
    'Import a component from its file, for example `@/renderer/design-system/atoms/AppButton.vue`, or from the index `@/renderer/design-system`.',
    '',
  ];
  const missing = [];
  for (const [level, title, summary] of LEVELS) {
    lines.push(`## ${title}`, '', summary, '');
    for (const name of readdirSync(join(base, level)).filter((entry) => entry.endsWith('.vue')).sort()) {
      const file = join(base, level, name);
      const meta = checker.getComponentMeta(file);
      const text = description(file);
      if (!text) missing.push(`${level}/${name}`);
      const story = readdirSync(join(base, level)).includes(name.replace(/\.vue$/, '.stories.ts'));
      lines.push(`### ${name.replace(/\.vue$/, '')}`, '', text, '', `- File: \`src/renderer/design-system/${level}/${name}\`${story ? `\n- Story: \`src/renderer/design-system/${level}/${name.replace(/\.vue$/, '.stories.ts')}\`` : ''}`, '');
      const props = meta.props.filter((prop) => !prop.global).sort((a, b) => Number(b.required) - Number(a.required) || a.name.localeCompare(b.name));
      if (props.length) {
        lines.push('| Prop | Type | Required | Default | Description |', '| --- | --- | --- | --- | --- |');
        for (const prop of props) lines.push(`| ${code(prop.name)} | ${code(prop.type)} | ${prop.required ? 'yes' : 'no'} | ${prop.default ? code(prop.default) : ''} | ${cell(prop.description)} |`);
        lines.push('');
      }
      const events = meta.events.filter((event) => !props.some((prop) => prop.name === `on${event.name[0].toUpperCase()}${event.name.slice(1)}`) || true);
      if (events.length) {
        lines.push('| Event | Payload | Description |', '| --- | --- | --- |');
        for (const event of [...events].sort((a, b) => a.name.localeCompare(b.name))) lines.push(`| ${code(event.name)} | ${code(event.type)} | ${cell(event.description)} |`);
        lines.push('');
      }
      if (meta.slots.length) {
        lines.push('| Slot | Description |', '| --- | --- |');
        for (const slot of [...meta.slots].sort((a, b) => a.name.localeCompare(b.name))) lines.push(`| ${code(slot.name)} | ${cell(slot.description)} |`);
        lines.push('');
      }
      const exposed = meta.exposed.filter((entry) => !entry.name.startsWith('$') && !props.some((prop) => prop.name === entry.name) && !entry.name.startsWith('on'));
      if (exposed.length) {
        lines.push('| Exposed | Type | Description |', '| --- | --- | --- |');
        for (const entry of [...exposed].sort((a, b) => a.name.localeCompare(b.name))) lines.push(`| ${code(entry.name)} | ${code(entry.type)} | ${cell(entry.description)} |`);
        lines.push('');
      }
    }
  }
  return { text: `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`, missing };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { text, missing } = buildManifest();
  if (missing.length) { console.error(`Components without an "<!-- @component … -->" description: ${missing.join(', ')}`); process.exit(1); }
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n'); } catch { /* not written yet */ }
    if (current !== text) { console.error('docs/design-system/manifest.md is out of date. Run: npm run design-system:manifest'); process.exit(1); }
    console.log('docs/design-system/manifest.md is up to date.');
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
    console.log(`Wrote ${target}`);
  }
}
