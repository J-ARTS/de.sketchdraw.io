#!/usr/bin/env node
/**
 * Extracts the white glyphs of the AWS group header icons from the official AWS catalog (#143).
 *
 *   node scripts/generate-aws-group-glyphs.mjs
 *
 * Group headers are drawn as a square tile in the group color with a white glyph on it, like draw.io's
 * `mxgraph.aws4.group`. The official group icons already contain that glyph; AWS has no group icon for
 * Elastic Beanstalk, Step Functions and IoT Greengrass, so their service glyphs (80 x 80) are scaled to the
 * 40 x 40 tile instead. Output: src/catalog/aws-group-glyphs.ts
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(await readFile(join(ROOT, 'src/catalog/official/aws.json'), 'utf8'));
const icons = new Map(catalog.sets.flatMap((set) => set.components.map((component) => [component.type, component.iconSvg])));

/** group id -> official component whose glyph is used */
const SOURCES = {
  'aws.group.cloud-alt': 'aws.gruppen.aws-cloud',
  'aws.group.cloud': 'aws.gruppen.aws-cloud-logo',
  'aws.group.region': 'aws.gruppen.region',
  'aws.group.auto-scaling-group': 'aws.gruppen.auto-scaling-group',
  'aws.group.vpc': 'aws.gruppen.virtual-private-cloud-vpc',
  'aws.group.private-subnet': 'aws.gruppen.private-subnet',
  'aws.group.public-subnet': 'aws.gruppen.public-subnet',
  'aws.group.server-contents': 'aws.gruppen.server-contents',
  'aws.group.corporate-data-center': 'aws.gruppen.corporate-data-center',
  'aws.group.elastic-beanstalk': 'aws.compute.aws-elastic-beanstalk',
  'aws.group.ec2-instance-contents': 'aws.gruppen.ec2-instance-contents',
  'aws.group.spot-fleet': 'aws.gruppen.spot-fleet',
  'aws.group.step-functions': 'aws.application-integration.aws-step-functions',
  'aws.group.account': 'aws.gruppen.aws-account',
  'aws.group.iot-greengrass-deployment': 'aws.gruppen.aws-iot-greengrass-deployment',
  'aws.group.iot-greengrass': 'aws.internet-of-things.aws-iot-greengrass',
};

function glyphOf(type) {
  const svg = icons.get(type);
  if (!svg) throw new Error(`Missing catalog icon ${type}`);
  const group = svg.match(/^<svg viewBox="0 0 40 40"[^>]*><g [^>]*><rect [^>]*><\/rect>([\s\S]*)<\/g><\/svg>$/);
  const service = svg.match(/^<svg viewBox="0 0 80 80"[^>]*><g [^>]*><g fill="#[0-9A-Fa-f]{6}"><rect [^>]*><\/rect><\/g>([\s\S]*)<\/g><\/svg>$/);
  const body = (group ?? service)?.[1];
  if (!body) throw new Error(`Unexpected icon structure for ${type}`);
  const paths = body.replace(/ fill="#FFFFFF"/gi, '');
  if (/fill=|<rect|<g/.test(paths)) throw new Error(`Glyph of ${type} is not a plain white path list`);
  return service ? `<g transform="scale(.5)" fill="#FFFFFF" fill-rule="evenodd">${paths}</g>` : `<g fill="#FFFFFF" fill-rule="evenodd">${paths}</g>`;
}

const entries = Object.entries(SOURCES).map(([id, type]) => `  ${JSON.stringify(id)}: ${JSON.stringify(glyphOf(type))},`);
const header = `// Generated by scripts/generate-aws-group-glyphs.mjs from src/catalog/official/aws.json (AWS Architecture Icons). Do not edit.
/** White glyphs of the AWS group header tiles in a 40 x 40 box, keyed by group id. */
export const AWS_GROUP_GLYPHS: Readonly<Record<string, string>> = Object.freeze({
`;
await writeFile(join(ROOT, 'src/catalog/aws-group-glyphs.ts'), `${header}${entries.join('\n')}\n});\n`);
console.log(`Wrote ${entries.length} glyphs`);
