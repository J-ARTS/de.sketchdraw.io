import { createAnnotationDocument, type AnnotationBlock, type AnnotationBlockType, type AnnotationDocument, type AnnotationRun } from '@/domain';

export type AnnotationFormatCommand =
  | 'paragraph' | 'heading-1' | 'heading-2' | 'heading-3' | 'heading-4'
  | 'bold' | 'italic' | 'underline' | 'color' | 'bullet' | 'numbered' | 'quote';

export const ANNOTATION_FORMAT_EVENT = 'sketchdraw:annotation-format';

export function dispatchAnnotationFormat(command: AnnotationFormatCommand, value?: string): void {
  window.dispatchEvent(new CustomEvent(ANNOTATION_FORMAT_EVENT, { detail: { command, value } }));
}

function marksEqual(a: AnnotationRun, b: AnnotationRun): boolean {
  return a.bold === b.bold && a.italic === b.italic && a.underline === b.underline && a.color === b.color;
}

function appendRun(runs: AnnotationRun[], run: AnnotationRun): void {
  const previous = runs.at(-1);
  if (previous && marksEqual(previous, run)) previous.text += run.text;
  else runs.push(run);
}

interface Marks { bold?: true; italic?: true; underline?: true; color?: string }

function inlineRuns(node: Node, inherited: Marks = {}): AnnotationRun[] {
  if (node.nodeType === Node.TEXT_NODE) return [{ text: node.textContent ?? '', ...inherited }];
  if (!(node instanceof HTMLElement)) return [];
  if (node.tagName === 'BR') return [{ text: '\n', ...inherited }];
  const marks: Marks = { ...inherited };
  const tag = node.tagName;
  if (tag === 'B' || tag === 'STRONG' || Number.parseInt(node.style.fontWeight || '0', 10) >= 600) marks.bold = true;
  if (tag === 'I' || tag === 'EM' || node.style.fontStyle === 'italic') marks.italic = true;
  if (tag === 'U' || node.style.textDecorationLine.includes('underline')) marks.underline = true;
  const color = node.getAttribute('color') ?? node.style.color;
  if (color) {
    const context = document.createElement('canvas').getContext('2d');
    if (context) {
      context.fillStyle = '#000000';
      context.fillStyle = color;
      const normalized = context.fillStyle;
      if (/^#[0-9a-f]{6}$/i.test(normalized)) marks.color = normalized.toLowerCase();
      else {
        const short = /^#([0-9a-f])([0-9a-f])([0-9a-f])$/i.exec(normalized);
        if (short) marks.color = `#${short[1]}${short[1]}${short[2]}${short[2]}${short[3]}${short[3]}`.toLowerCase();
      }
    }
  }
  const runs: AnnotationRun[] = [];
  for (const child of node.childNodes) for (const run of inlineRuns(child, marks)) appendRun(runs, run);
  return runs;
}

function typeFor(element: HTMLElement): AnnotationBlockType {
  if (element.tagName === 'H1') return 'heading-1';
  if (element.tagName === 'H2') return 'heading-2';
  if (element.tagName === 'H3') return 'heading-3';
  if (element.tagName === 'H4') return 'heading-4';
  if (element.tagName === 'BLOCKQUOTE') return 'quote';
  if (element.tagName === 'LI') return element.parentElement?.tagName === 'OL' ? 'numbered' : 'bullet';
  return 'paragraph';
}

function blockFrom(element: HTMLElement): AnnotationBlock {
  return { type: typeFor(element), runs: inlineRuns(element).filter((run) => run.text.length > 0) };
}

export function annotationFromEditable(root: HTMLElement): AnnotationDocument {
  const blocks: AnnotationBlock[] = [];
  let looseRuns: AnnotationRun[] = [];
  const flushLoose = () => {
    if (looseRuns.length) {
      blocks.push({ type: 'paragraph', runs: looseRuns });
      looseRuns = [];
    }
  };
  const appendElement = (element: HTMLElement): void => {
    if (element.tagName === 'UL' || element.tagName === 'OL') {
      for (const item of element.children) if (item instanceof HTMLElement && item.tagName === 'LI') blocks.push(blockFrom(item));
      return;
    }
    // Chromium may wrap a list generated by execCommand in the selected paragraph.
    // Treat direct nested lists as blocks instead of flattening them back to a paragraph.
    const nestedLists = Array.from(element.children).filter((child): child is HTMLElement => child instanceof HTMLElement && (child.tagName === 'UL' || child.tagName === 'OL'));
    if (nestedLists.length) {
      for (const list of nestedLists) appendElement(list);
      return;
    }
    blocks.push(blockFrom(element));
  };
  for (const child of root.childNodes) {
    if (child.nodeType === Node.TEXT_NODE) {
      for (const run of inlineRuns(child)) appendRun(looseRuns, run);
      continue;
    }
    if (!(child instanceof HTMLElement)) continue;
    flushLoose();
    appendElement(child);
  }
  flushLoose();
  const normalized = blocks.map((block) => ({ ...block, runs: block.runs.length ? block.runs : [{ text: '' }] }));
  return normalized.length ? { version: 1, blocks: normalized } : createAnnotationDocument();
}

function escapeHtml(value: string): string {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
}

function runHtml(run: AnnotationRun): string {
  let value = escapeHtml(run.text).replaceAll('\n', '<br>');
  if (run.color) value = `<span style="color:${escapeHtml(run.color)}">${value}</span>`;
  if (run.underline) value = `<u>${value}</u>`;
  if (run.italic) value = `<em>${value}</em>`;
  if (run.bold) value = `<strong>${value}</strong>`;
  return value;
}

const BLOCK_TAGS: Record<Exclude<AnnotationBlockType, 'bullet' | 'numbered'>, string> = {
  paragraph: 'p', 'heading-1': 'h1', 'heading-2': 'h2', 'heading-3': 'h3', 'heading-4': 'h4', quote: 'blockquote',
};

export function annotationToEditorHtml(documentValue: AnnotationDocument): string {
  let html = '';
  let openList: 'bullet' | 'numbered' | null = null;
  const closeList = () => {
    if (openList) html += openList === 'bullet' ? '</ul>' : '</ol>';
    openList = null;
  };
  for (const block of documentValue.blocks) {
    const content = block.runs.map(runHtml).join('') || '<br>';
    if (block.type === 'bullet' || block.type === 'numbered') {
      if (openList !== block.type) {
        closeList();
        html += block.type === 'bullet' ? '<ul>' : '<ol>';
        openList = block.type;
      }
      html += `<li>${content}</li>`;
    } else {
      closeList();
      const tag = BLOCK_TAGS[block.type];
      html += `<${tag}>${content}</${tag}>`;
    }
  }
  closeList();
  return html;
}
